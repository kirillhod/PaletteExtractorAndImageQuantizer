/**
 * Generate a deterministic 64×64 void-and-cluster blue-noise mask.
 *
 * The mask is committed as a runtime asset and embedded as base64 in a JS module so the
 * browser never fetches it at runtime. Run from the repository root:
 *
 *   node tools/gen-blue-noise.mjs
 */

import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRng } from '../js/core/rng.js';
import { encodeRgbaPng } from '../js/core/png/encode.js';

const SIZE = 64;
const TOTAL = SIZE * SIZE;
const HALF = TOTAL >> 1;
const SIGMA = 1.5;
const RADIUS = 4;

const kernel = [];
for (let dy = -RADIUS; dy <= RADIUS; dy++) {
  for (let dx = -RADIUS; dx <= RADIUS; dx++) {
    const distance = dx * dx + dy * dy;
    kernel.push({ dx, dy, weight: Math.exp(-distance / (2 * SIGMA * SIGMA)) });
  }
}

const pattern = new Uint8Array(TOTAL);
const energy = new Float64Array(TOTAL);
const ranks = new Uint16Array(TOTAL);

const rng = createRng(0x5eed);
const order = Array.from({ length: TOTAL }, (_, index) => index);
for (let i = order.length - 1; i > 0; i--) {
  const j = rng.nextInt(i + 1);
  [order[i], order[j]] = [order[j], order[i]];
}
for (let i = 0; i < HALF; i++) pattern[order[i]] = 1;

function wrap(value) {
  return ((value % SIZE) + SIZE) % SIZE;
}

function toggle(index, on) {
  const x = index % SIZE;
  const y = (index / SIZE) | 0;
  pattern[index] = on ? 1 : 0;
  for (const tap of kernel) {
    const target = wrap(y + tap.dy) * SIZE + wrap(x + tap.dx);
    energy[target] += on ? tap.weight : -tap.weight;
  }
}

for (let i = 0; i < TOTAL; i++) if (pattern[i]) toggle(i, true);

function tightestCluster() {
  let best = -1;
  let bestEnergy = -Infinity;
  for (let i = 0; i < TOTAL; i++) {
    if (!pattern[i]) continue;
    if (energy[i] > bestEnergy || (energy[i] === bestEnergy && i < best)) {
      bestEnergy = energy[i];
      best = i;
    }
  }
  return best;
}

function largestVoid() {
  let best = -1;
  let bestEnergy = Infinity;
  for (let i = 0; i < TOTAL; i++) {
    if (pattern[i]) continue;
    if (energy[i] < bestEnergy || (energy[i] === bestEnergy && i < best)) {
      bestEnergy = energy[i];
      best = i;
    }
  }
  return best;
}

// Optimize the 50% prototype.
for (let iteration = 0; iteration < 4000; iteration++) {
  const cluster = tightestCluster();
  const hole = largestVoid();
  if (cluster < 0 || hole < 0) break;
  if (energy[cluster] <= energy[hole] + 1e-12) break;
  toggle(cluster, false);
  toggle(hole, true);
}

// Save the stable prototype for the fill half.
const prototype = pattern.slice();
const prototypeEnergy = energy.slice();

// Rank the ones: remove the tightest cluster repeatedly.
for (let rank = 0; rank < HALF; rank++) {
  const cluster = tightestCluster();
  if (cluster < 0) throw new Error('prototype ran out of pixels while ranking');
  ranks[cluster] = rank;
  toggle(cluster, false);
}

// Restore the prototype, then fill the largest voids.
pattern.set(prototype);
energy.set(prototypeEnergy);
for (let rank = HALF; rank < TOTAL; rank++) {
  const hole = largestVoid();
  if (hole < 0) throw new Error('prototype ran out of voids while ranking');
  ranks[hole] = rank;
  toggle(hole, true);
}

const mask = new Uint8Array(TOTAL);
for (let i = 0; i < TOTAL; i++) {
  mask[i] = Math.round((ranks[i] / (TOTAL - 1)) * 255);
}

fs.mkdirSync('assets', { recursive: true });
fs.mkdirSync('js/core/dither', { recursive: true });
fs.writeFileSync('assets/blue-noise-64.bin', mask);

const base64 = Buffer.from(mask).toString('base64');
fs.writeFileSync(
  'js/core/dither/blue-noise-mask.js',
  `// @ts-check\n// Generated by tools/gen-blue-noise.mjs. Do not edit by hand.\n` +
    `export const BLUE_NOISE_64_B64 = '${base64}';\n`,
);

const checksum = createHash('sha256').update(mask).digest('hex');
console.log(`blue-noise-64.bin: ${mask.length} bytes, sha256 ${checksum}`);

// Optional visual check (not committed).
const preview = new Uint8ClampedArray(SIZE * 8 * SIZE * 8 * 4);
for (let y = 0; y < SIZE * 8; y++) {
  for (let x = 0; x < SIZE * 8; x++) {
    const value = mask[((y / 8) | 0) * SIZE + ((x / 8) | 0)];
    const offset = (y * SIZE * 8 + x) * 4;
    preview[offset] = value;
    preview[offset + 1] = value;
    preview[offset + 2] = value;
    preview[offset + 3] = 255;
  }
}
const png = await encodeRgbaPng(SIZE * 8, SIZE * 8, preview);
const previewPath = join(tmpdir(), 'peiq-blue-noise-preview.png');
fs.writeFileSync(previewPath, png);
console.log(`preview: ${previewPath}`);
